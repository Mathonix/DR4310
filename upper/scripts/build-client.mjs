import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const outfile = path.join(root, "dist", "client.js");
const genfile = path.join(root, "src", "client-bundle.ts");

fs.mkdirSync(path.dirname(outfile), { recursive: true });

if (!process.argv.includes("--embed-only")) await esbuild.build({
  entryPoints: [path.join(root, "src", "client.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2020"],
  outfile,
  logLevel: "info",
});

const js = fs.readFileSync(outfile, "utf8");
fs.writeFileSync(
  genfile,
  `/* auto-generated by scripts/build-client.mjs — do not edit */\nexport const CLIENT_JS = ${JSON.stringify(js)};\n`
);
console.log("Wrote", genfile, "(" + js.length + " bytes JS)");
